-- Staging tables for the pre-lock Fantasy Points live matchup captures
-- (loader: src/nfl_dfs/ingest/fantasy_points_matchups_weekly.py).
--
-- One row per vendor row per capture. Append key
-- (season, target_week, report, source_sha256, source_row) is a pure function
-- of the export bytes; a second capture of the same target week appends beside
-- the first. Nothing under sql/features/ reads these tables; the shadow join
-- (sql/research/fp_matchup_shadow_tables.sql) is the only consumer.
--
-- Column order and names are asserted equal to the loader's output by
-- tests/test_fp_matchup_ddl.py; change both together.

CREATE TABLE IF NOT EXISTS `${raw}.fantasy_points_qb_coverage_matchup_weekly` (
  season INT64 NOT NULL,
  target_week INT64 NOT NULL,
  report STRING NOT NULL,
  source_sha256 STRING NOT NULL,
  source_row INT64 NOT NULL,
  team STRING NOT NULL,
  opponent STRING NOT NULL,
  identity STRING NOT NULL,
  gsis_id STRING,
  resolution_status STRING NOT NULL,
  vendor_name STRING NOT NULL,
  normalized_name STRING,
  vendor_team STRING NOT NULL,
  canonical_teams STRING NOT NULL,
  vendor_pos STRING,
  pos STRING,
  games INT64,
  source_season INT64 NOT NULL,
  source_regime STRING NOT NULL,
  matchup__db FLOAT64,
  matchup__db_per_g FLOAT64,
  matchup__fp_per_db FLOAT64,
  matchup__exp_fp_per_db FLOAT64,
  matchup__cov_grade FLOAT64,
  man__def_man_pct FLOAT64,
  man__def_fp_per_db FLOAT64,
  man__qb_man_pct FLOAT64,
  man__qb_fp_per_db FLOAT64,
  cover_2__def_cover_2_pct FLOAT64,
  cover_2__def_fp_per_db FLOAT64,
  cover_2__qb_cover_2_pct FLOAT64,
  cover_2__qb_fp_per_db FLOAT64,
  cover_3__def_cover_3_pct FLOAT64,
  cover_3__def_fp_per_db FLOAT64,
  cover_3__qb_cover_3_pct FLOAT64,
  cover_3__qb_fp_per_db FLOAT64,
  cover_4__def_cover_4_pct FLOAT64,
  cover_4__def_fp_per_db FLOAT64,
  cover_4__qb_cover_4_pct FLOAT64,
  cover_4__qb_fp_per_db FLOAT64,
  cover_6__def_cover_6_pct FLOAT64,
  cover_6__def_fp_per_db FLOAT64,
  cover_6__qb_cover_6_pct FLOAT64,
  cover_6__qb_fp_per_db FLOAT64,
  source_file STRING NOT NULL,
  source_retrieved_at TIMESTAMP NOT NULL,
  source_run_id STRING NOT NULL,
  source_attempt INT64 NOT NULL,
  first_kickoff_utc TIMESTAMP NOT NULL,
  capture_ref STRING NOT NULL,
  archive_uri STRING,
  ingested_at TIMESTAMP NOT NULL
)
PARTITION BY DATE(source_retrieved_at)
CLUSTER BY season, target_week, source_sha256;

